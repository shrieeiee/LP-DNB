#!/usr/bin/env python3
"""Regenerates src/fonts_data.cpp from assets/fonts/*.ttf (run from the repo root)."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
fonts = {"kFontBody": "Nunito-SemiBold-subset.ttf", "kFontBold": "Nunito-ExtraBold-subset.ttf"}
out = ["// Generated by tools/embed_fonts.py - do not edit.",
       "// Nunito by Vernon Adams et al., SIL Open Font License 1.1 (assets/fonts/OFL.txt).",
       '#include "fonts_data.h"', "", "namespace dnb {", ""]
for var, name in fonts.items():
    data = (root / "assets" / "fonts" / name).read_bytes()
    out.append(f"const unsigned int {var}Size = {len(data)};")
    out.append(f"const unsigned char {var}[{len(data)}] = {{")
    for i in range(0, len(data), 20):
        out.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    out.append("};")
    out.append("")
out.append("}  // namespace dnb")
(root / "src" / "fonts_data.cpp").write_text("\n".join(out) + "\n")
print("wrote src/fonts_data.cpp")
