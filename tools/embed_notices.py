#!/usr/bin/env python3
"""Regenerates src/notices_data.cpp from THIRD-PARTY-NOTICES.txt (run from the repo root),
so the licences travel inside the program as well as next to it."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
text = (root / "THIRD-PARTY-NOTICES.txt").read_text(encoding="utf-8")
out = ["// Generated by tools/embed_notices.py from THIRD-PARTY-NOTICES.txt - do not edit.",
       '#include "notices_data.h"', "", "namespace dnb {", "", "const char* const kThirdPartyNotices ="]
for line in text.splitlines():
    out.append("    " + json.dumps(line + "\n", ensure_ascii=True))  # one short literal per line
out[-1] += ";"
out += ["", "}  // namespace dnb", ""]
(root / "src" / "notices_data.cpp").write_text("\n".join(out), encoding="utf-8")
print("wrote src/notices_data.cpp")
